#!/usr/bin/env python3
"""Build a single-file LimeShift demo using the current root HTML/CSS/JS/assets.

Usage: python scripts/build_preview.py
Output: preview/limeshift-ayra-standalone.html
Fonts may still load from Google Fonts; fallback families render when offline.
"""
from __future__ import annotations
from pathlib import Path
from base64 import b64encode
import mimetypes
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "preview" / "limeshift-ayra-standalone.html"
RESOURCE_PATTERN = re.compile(r"assets/[A-Za-z0-9_.-]+")

def main():
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    for name in ("styles.css", "fidelity.css"):
        token = f'<link rel="stylesheet" href="{name}">'
        if token not in html:
            raise ValueError(f"Expected stylesheet reference missing: {name}")
        css = (ROOT / name).read_text(encoding="utf-8")
        html = html.replace(token, "<style>\n" + css + "\n</style>", 1)

    code = []
    for name in ("app.js", "fidelity.js"):
        token = f'<script defer src="{name}"></script>'
        if token not in html:
            raise ValueError(f"Expected script reference missing: {name}")
        html = html.replace(token, "", 1)
        script = (ROOT / name).read_text(encoding="utf-8")
        if "</script" in script.lower():
            raise ValueError(f"Script closing tag must be escaped before inline export: {name}")
        code.append("<script>\n" + script + "\n</script>")
    html = html.replace("</body>", "\n" + "\n".join(code) + "\n</body>", 1)
    cache = {}
    def inline_asset(match):
        path = match.group(0)
        if path not in cache:
            resource = ROOT / path
            if not resource.is_file():
                raise FileNotFoundError(resource)
            kind = mimetypes.guess_type(resource.name)[0] or "application/octet-stream"
            cache[path] = f"data:{kind};base64," + b64encode(resource.read_bytes()).decode("ascii")
        return cache[path]

    html = RESOURCE_PATTERN.sub(inline_asset, html)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("<!-- Generated by scripts/build_preview.py. Do not edit directly. -->\n" + html, encoding="utf-8")
    print(f"Built {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size:,} bytes, {len(cache)} embedded assets)")

if __name__ == "__main__":
    main()
